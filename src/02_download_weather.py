"""
Step 6: Download daily weather data from the Open-Meteo Historical Weather API
for all Indonesia grid points, processing one year at a time and saving
the results as yearly Parquet files.

Important design: resume at the GRID-POINT level, not just the year level.
- Read grid points from metadata/grid_points.csv, generated by 01_generate_grid.py.
- If a final file (agroclimate_<year>.parquet) already exists, skip that year.
- If a partial file (agroclimate_<year>_partial.parquet) exists, identify
  successfully downloaded grid points and download only the remaining points.
- When the server returns "Daily API request limit exceeded", save all progress
  to the partial file and stop immediately. Do not retry or continue to other
  points or years until the quota becomes available again.
- Other errors, such as network interruptions or temporary throttling, are
  retried with backoff up to MAX_RETRIES.

Usage:
    python 02_download_weather.py
    python 02_download_weather.py --start-year 2020 --end-year 2021
    python 02_download_weather.py --limit-points 20
"""

import argparse
import datetime as dt
import sys
import time
from pathlib import Path

import pandas as pd
import requests

import config


class QuotaExceeded(RuntimeError):
    """Raised when the Open-Meteo API quota is exceeded.
    Retrying is ineffective until the quota becomes available again."""


def fetch_batch(latitudes, longitudes, start_date, end_date):
    params = {
        "latitude": ",".join(f"{lat:.4f}" for lat in latitudes),
        "longitude": ",".join(f"{lon:.4f}" for lon in longitudes),
        "start_date": start_date,
        "end_date": end_date,
        "daily": ",".join(config.DAILY_VARIABLES),
        "timezone": config.TIMEZONE,
        "models": config.WEATHER_MODEL,
    }

    last_error = None

    for attempt in range(1, config.MAX_RETRIES + 1):
        try:
            resp = requests.get(
                config.ARCHIVE_API_URL,
                params=params,
                timeout=60
            )

            if resp.status_code == 429:
                try:
                    body = resp.json()
                except ValueError:
                    body = {}

                reason = str(body.get("reason", ""))

                if "limit" in reason.lower() and (
                    "exceeded" in reason.lower()
                    or "limit" in reason.lower()
                ):
                    raise QuotaExceeded(
                        reason or "API request limit exceeded"
                    )

                wait = config.RETRY_BACKOFF_SECONDS * attempt
                print(
                    f"    [rate limited, not a daily quota error] "
                    f"waiting {wait}s ({attempt}/{config.MAX_RETRIES}) ..."
                )
                time.sleep(wait)
                continue

            resp.raise_for_status()
            return resp.json()

        except QuotaExceeded:
            raise

        except (requests.RequestException, ValueError) as exc:
            last_error = exc
            wait = config.RETRY_BACKOFF_SECONDS * attempt
            print(
                f"    [error] {exc} - retrying in {wait}s "
                f"({attempt}/{config.MAX_RETRIES}) ..."
            )
            time.sleep(wait)

    raise RuntimeError(
        f"Failed after {config.MAX_RETRIES} attempts: {last_error}"
    )


def batch_json_to_dataframe(payload, grid_ids, latitudes, longitudes):
    records = payload if isinstance(payload, list) else [payload]
    frames = []

    for grid_id, lat, lon, record in zip(
        grid_ids, latitudes, longitudes, records
    ):
        if "daily" not in record:
            print(
                f"    [warning] no 'daily' data for grid_id={grid_id}; skipped"
            )
            continue

        df = pd.DataFrame(record["daily"]).rename(
            columns={"time": "date"}
        )
        df.insert(0, "grid_id", grid_id)
        df.insert(1, "latitude", record.get("latitude", lat))
        df.insert(2, "longitude", record.get("longitude", lon))
        frames.append(df)

    return (
        pd.concat(frames, ignore_index=True)
        if frames
        else pd.DataFrame()
    )


def save_partial(existing_df, new_frames, partial_path):
    """Combine previous progress, if available, with new data and save it."""
    frames = []

    if existing_df is not None and not existing_df.empty:
        frames.append(existing_df)

    frames.extend(new_frames)

    if not frames:
        return None

    combined = pd.concat(frames, ignore_index=True)
    combined.to_parquet(partial_path, index=False)

    return combined


def download_year(grid, year, batch_size, output_dir):
    out_path = output_dir / f"agroclimate_{year}.parquet"
    partial_path = output_dir / f"agroclimate_{year}_partial.parquet"

    if out_path.exists():
        print(f"[{year}] final file already exists; skipping")
        return out_path

    # Resume from the partial file and download only unfinished grid points.
    existing_df = None
    remaining_grid = grid

    if partial_path.exists():
        existing_df = pd.read_parquet(partial_path)
        done_grid_ids = set(existing_df["grid_id"].unique())

        remaining_grid = grid[
            ~grid["grid_id"].isin(done_grid_ids)
        ].reset_index(drop=True)

        print(
            f"[{year}] previous progress found: "
            f"{len(done_grid_ids)}/{len(grid)} grid points completed; "
            f"continuing with {len(remaining_grid)} remaining points"
        )

    if remaining_grid.empty:
        # All grid points are already present in the partial file; finalize it.
        out_path.parent.mkdir(parents=True, exist_ok=True)

        final_df = existing_df.copy()
        final_df["date"] = pd.to_datetime(final_df["date"])
        final_df = final_df.sort_values(
            ["grid_id", "date"]
        ).reset_index(drop=True)

        final_df.to_parquet(out_path, index=False)
        partial_path.unlink(missing_ok=True)

        print(
            f"[{year}] completed from previous progress: "
            f"{len(final_df):,} rows -> {out_path}"
        )
        return out_path

    start_date = f"{year}-01-01"
    today = dt.date.today()
    end_date = f"{year}-12-31"

    if dt.date(year, 12, 31) > today:
        end_date = today.isoformat()

        if dt.date(year, 1, 1) > today:
            return out_path

    n_points = len(remaining_grid)
    n_batches = -(-n_points // batch_size)

    print(
        f"[{year}] downloading {n_points:,} remaining grid points "
        f"in {n_batches} batches ({start_date} to {end_date}) ..."
    )

    new_frames, failed_batches = [], []

    for i in range(0, n_points, batch_size):
        batch = remaining_grid.iloc[i:i + batch_size]
        batch_num = i // batch_size + 1

        print(f"  batch {batch_num}/{n_batches} ...")

        try:
            payload = fetch_batch(
                batch["latitude"].tolist(),
                batch["longitude"].tolist(),
                start_date,
                end_date
            )

            df = batch_json_to_dataframe(
                payload,
                batch["grid_id"].tolist(),
                batch["latitude"].tolist(),
                batch["longitude"].tolist()
            )

            if not df.empty:
                new_frames.append(df)

        except QuotaExceeded:
            save_partial(existing_df, new_frames, partial_path)

            n_done = (
                len(existing_df) if existing_df is not None else 0
            ) + sum(len(frame) for frame in new_frames)

            print(
                f"[{year}] progress saved to {partial_path} "
                f"({n_done:,} rows collected)"
            )
            raise

        except RuntimeError as exc:
            print(
                f"    [SKIP] batch {batch_num} failed and was skipped: {exc}"
            )
            failed_batches.append(batch_num)

        time.sleep(config.REQUEST_SLEEP_SECONDS)

    if not new_frames and existing_df is None:
        print(f"[{year}] no data retrieved")
        return out_path

    if failed_batches:
        save_partial(existing_df, new_frames, partial_path)

        print(
            f"[{year}] {len(failed_batches)} batches failed; "
            f"progress saved to {partial_path}"
        )
        raise RuntimeError(f"{len(failed_batches)} batches failed")

    # Combine completed downloads with previous progress and finalize the file.
    combined = save_partial(
        existing_df,
        new_frames,
        partial_path
    )

    combined["date"] = pd.to_datetime(combined["date"])
    combined = combined.sort_values(
        ["grid_id", "date"]
    ).reset_index(drop=True)

    out_path.parent.mkdir(parents=True, exist_ok=True)
    combined.to_parquet(out_path, index=False)
    partial_path.unlink(missing_ok=True)

    print(
        f"[{year}] completed: {len(combined):,} rows -> {out_path}"
    )

    return out_path


def main():
    parser = argparse.ArgumentParser(description=__doc__)

    parser.add_argument("--grid", type=Path, default=config.GRID_PATH)
    parser.add_argument(
        "--start-year",
        type=int,
        default=config.START_YEAR
    )
    parser.add_argument(
        "--end-year",
        type=int,
        default=config.END_YEAR
    )
    parser.add_argument(
        "--batch-size",
        type=int,
        default=config.BATCH_SIZE
    )
    parser.add_argument(
        "--output-dir",
        type=Path,
        default=config.RAW_DIR
    )
    parser.add_argument(
        "--limit-points",
        type=int,
        default=None
    )

    args = parser.parse_args()

    if not args.grid.exists():
        print(
            f"ERROR: grid file not found at {args.grid}. "
            "Run 01_generate_grid.py first.",
            file=sys.stderr
        )
        sys.exit(1)

    grid = pd.read_csv(args.grid)

    if args.limit_points:
        grid = grid.head(args.limit_points)
        print(f"[debug] limiting download to the first {len(grid)} grid points")

    failed_years = []

    for year in range(args.start_year, args.end_year + 1):
        try:
            download_year(
                grid,
                year,
                args.batch_size,
                args.output_dir
            )

        except QuotaExceeded as exc:
            print("\n=== API QUOTA EXCEEDED ===")
            print(f"Server message: {exc}")
            print(
                f"Stopped at year {year}. Wait until the quota becomes "
                "available again, then rerun the same command. Successfully "
                "downloaded grid points will not be downloaded again."
            )
            sys.exit(0)

        except RuntimeError as exc:
            print(
                f"[{year}] FAILED; continuing to the next year: {exc}"
            )
            failed_years.append(year)

    if failed_years:
        print(
            f"\nFinished, BUT these years failed: {failed_years}. "
            "Rerun the same command to retry."
        )
    else:
        print("\nAll years completed.")


if __name__ == "__main__":
    main()